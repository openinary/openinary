/**
 * The Postgres schema. A fresh database only ever starts at the current
 * shape, so unlike SQLite there are no legacy upgrade steps: version 1 is
 * the whole schema, created idempotently. Better Auth's tables use the types
 * its own Postgres migrations generate (boolean, timestamptz); the app's
 * tables keep epoch-ms integers as BIGINT so app code is the same on both
 * dialects. Identifiers are quoted: Better Auth's columns are camelCase and
 * "user" is reserved.
 */

