// The site runs as a Cloudflare Worker, which has no filesystem: pages that
// read repo files must get them at build time. This writes them into a
// module the pages import (prebuild and predev run it).
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";

const read = (p) => readFileSync(new URL(p, import.meta.url), "utf8");

// Human contributors by commit count. Fetched here, not in the page: from the
// Worker, GitHub's per-IP rate limit is shared with strangers (CLAUDE.md, 4).
// Offline or rate-limited, the page falls back to the changelog's thanks.
async function contributorLogins() {
  try {
    const res = await fetch("https://api.github.com/repos/openinary/openinary/contributors?per_page=100", {
      headers: { Accept: "application/vnd.github+json" },
      signal: AbortSignal.timeout(10_000),
    });
    if (!res.ok) throw new Error(`GitHub ${res.status}`);
    return (await res.json()).filter((c) => c.type === "User").map((c) => c.login);
  } catch (err) {
    console.warn(`inline-sources: contributors skipped (${err.message})`);
    return [];
  }
}
mkdirSync(new URL("../lib/generated/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../lib/generated/sources.ts", import.meta.url),
  `// Generated by scripts/inline-sources.mjs. Do not edit.
export const CHANGELOG_MDX = ${JSON.stringify(read("../../docs/changelog.mdx"))};
export const DOCKER_COMPOSE_YML = ${JSON.stringify(read("../../../docker-compose.yml"))};
export const GITHUB_CONTRIBUTORS: string[] = ${JSON.stringify(await contributorLogins())};
`,
);
